#!/usr/bin/env python3
"""Writes the pin assignment section of fpga-arch/artix7/scaffold.xdc from
hw/rev2/fpga_pins.csv (produced by gen_fpga.py).

The port -> board net map below is the one of the Rev 1.1 Quartus project
(fpga-arch/scaffold.qsf joined with the Rev 1.1 netlist), so the gateware
top level is unchanged.

Run from the repository root:  python3 hw/rev2/tools/gen_xdc.py
"""
import csv

XDC = "fpga-arch/artix7/scaffold.xdc"
BEGIN = "# --- Pin assignments (generated by hw/rev2/tools/gen_xdc.py, do not edit) ---"
END = "# --- End of generated pin assignments ---"

PORTS = {"clock": "CLK_25M", "reset_n": "RESET_N", "tx": "TXD", "rx": "RXD",
         "leds_lat": "LED_LE", "leds_sclk": "LED_CLK", "leds_sin": "LED_SDI", "leds_blank": "LED_/OE",
         "power_platform": "EN_VCC_PLATFORM", "power_dut": "EN_VCC_DUT", "teardown": "TEARING",
         "pull_d0": "PULL_D0", "pull_d1": "PULL_D1", "pull_d2": "PULL_D2"}
for i in range(4):
    PORTS["io[%d]" % i] = "IO_A%d" % i
    PORTS["io_dir[%d]" % i] = "DIR_A%d" % i
for i in range(16):
    PORTS["io[%d]" % (4 + i)] = "IO%d_DUT" % i
    PORTS["io[%d]" % (20 + i)] = "IO%d_PLAT" % i


def main():
    pins = {r["net"]: r for r in csv.DictReader(open("hw/rev2/fpga_pins.csv"))}
    lines = [BEGIN]
    for port, net in PORTS.items():
        r = pins[net]
        lines.append("set_property PACKAGE_PIN %-4s [get_ports {%s}]   ;# %s, bank %s"
                     % (r["ball"], port, net, r["bank"]))
    unused = sorted(set(pins) - set(PORTS.values()))
    lines.append("# Board nets wired to the FPGA but not used by the gateware: "
                 + ", ".join("%s=%s" % (n, pins[n]["ball"]) for n in unused))
    lines.append(END)
    text = open(XDC).read()
    if BEGIN in text:
        text = text[:text.index(BEGIN)] + "\n".join(lines) + text[text.index(END) + len(END):]
    else:
        marker = "# --- Pin assignments (TODO: from Rev 2 PCB) ---\n# set_property PACKAGE_PIN <pin> [get_ports clock]\n"
        assert marker in text
        text = text.replace(marker, "\n".join(lines) + "\n")
    open(XDC, "w").write(text)
    print("wrote %d pin constraints to %s" % (len(PORTS), XDC))


if __name__ == "__main__":
    main()
